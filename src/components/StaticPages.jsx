import { ALL_QUESTIONS, EXAM, TOPICS, TRACKS } from '../data';
import { SITE } from '../site.config';
import { Breadcrumbs } from './Growth';
import { Link } from '../router';

function Contact() {
  const email = SITE.contactEmail;
  const wa = SITE.whatsapp;
  if (!email && !wa) return null;
  return (
    <section>
      <h2>تواصل معنا</h2>
      <p>وجدت خطأً في سؤال أو لديك اقتراح؟ يسعدنا أن نسمعك:</p>
      <ul className="bullets">
        {email && (
          <li>
            البريد: <a href={`mailto:${email}`}>{email}</a>
          </li>
        )}
        {wa && (
          <li>
            واتساب:{' '}
            <a href={`https://wa.me/${wa}`} target="_blank" rel="noopener noreferrer">
              راسلنا
            </a>
          </li>
        )}
      </ul>
    </section>
  );
}

